"""Render the checked-in bilingual guide/privacy pages. Requires Python mistune.
Run: python3 docs/build_pages.py. Browsers use static HTML; no Markdown runtime.
"""
from pathlib import Path
import html
import json
import re
import mistune

ROOT = Path(__file__).resolve().parent
VERSION = json.loads((ROOT.parent / 'manifest.json').read_text())['version']
markdown = mistune.create_markdown(escape=True, plugins=['table'])


def article(path, lang):
    source = path.read_text()
    title, body = source.split('\n', 1)
    title = title.lstrip('# ').strip()
    rendered = markdown(body)
    toc = []

    def heading(match):
        label = match[1]
        identifier = lang + '-section-' + str(len(toc) + 1)
        toc.append('<li><a href="#' + identifier + '">' + label + '</a></li>')
        return '<h2 id="' + identifier + '">' + label + '</h2>'

    rendered = re.sub(r'<h2>(.*?)</h2>', heading, rendered)
    rendered = rendered.replace('<table>', '<div class="table-scroll" tabindex="0" role="region" aria-label="' + ('Таблица сценариев' if lang == 'ru' else 'Reference table') + '"><table>').replace('</table>', '</table></div>')
    return title, rendered, '\n'.join(toc)


def build(filename, sources, descriptions, guide):
    title_en, _, _ = article(sources['en'], 'en')
    title_ru, _, _ = article(sources['ru'], 'ru')
    content = []
    for lang in ['en', 'ru']:
        title, rendered, toc = article(sources[lang], lang)
        content.append(f'''<div data-language="{lang}"{' hidden' if lang == 'ru' else ''}>
<header class="page-intro"><p class="eyebrow">GitLab MR Actions · {('Гайд' if guide else 'Приватность') if lang == 'ru' else ('Guide' if guide else 'Privacy')}</p><h1>{html.escape(title)}</h1><p class="summary">{html.escape(descriptions[lang])}</p></header>
<div class="reading-layout"><aside><nav aria-label="{'Оглавление' if lang == 'ru' else 'Contents'}"><p class="toc-title">{('Сценарии' if guide else 'Оглавление') if lang == 'ru' else ('Scenarios' if guide else 'Contents')}</p><ol>{toc}</ol></nav></aside><article>{rendered}</article></div></div>''')
    page = f'''<!DOCTYPE html>
<!-- Generated by docs/build_pages.py from the linked Markdown sources. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title_en)} — GitLab Actions</title>
<meta name="description" content="{html.escape(descriptions['en'], quote=True)}">
<meta name="referrer" content="no-referrer">
<link rel="canonical" href="https://termyanen.github.io/gitlab-actions/{filename}">
<link rel="icon" href="favicon-32.png"><link rel="stylesheet" href="guide.css"><script src="guide.js" defer></script>
</head><body data-title-en="{html.escape(title_en, quote=True)}" data-title-ru="{html.escape(title_ru, quote=True)}">
<a class="skip-link" href="#main">{'Skip to content / К содержимому'}</a>
<nav class="top-nav" aria-label="Main"><a href="./" class="brand"><img src="icon.png" width="28" height="28" alt="">GitLab Actions</a><div class="nav-actions"><a href="{'privacy.html' if guide else 'review-guide.html'}" data-en="{'Privacy' if guide else 'Review guide'}" data-ru="{'Приватность' if guide else 'Гайд по ревью'}">{'Privacy' if guide else 'Review guide'}</a><button type="button" data-switch="en" aria-pressed="true">EN</button><button type="button" data-switch="ru" aria-pressed="false">RU</button></div></nav>
<main id="main">{''.join(content)}</main>
<footer><a href="./" data-en="← All features" data-ru="← Все возможности">← All features</a><a href="https://github.com/termyanen/gitlab-actions" rel="noreferrer">GitHub</a><span>GitLab MR Actions · {VERSION}</span></footer>
</body></html>
'''
    (ROOT / filename).write_text(page)


build('review-guide.html', {'en': ROOT / 'AI_REVIEW_GUIDE_EN.md', 'ru': ROOT / 'AI_REVIEW_GUIDE_RU.md'}, {
    'en': 'What to click, what to give your AI, and how to check the result. For reviewers, authors and teams sharing one merge request.',
    'ru': 'Что нажимать, что передавать ИИ и как проверять результат. Для ревьюеров, авторов и команд, работающих над одним MR.'
}, True)
build('privacy.html', {'en': ROOT.parent / 'PRIVACY_POLICY.md', 'ru': ROOT / 'PRIVACY_POLICY_RU.md'}, {
    'en': 'How the extension uses GitLab data, local storage, clipboard export and optional integrations.',
    'ru': 'Как расширение использует данные GitLab, локальное хранилище, буфер обмена и опциональные интеграции.'
}, False)

for name in ["CHANGELOG.md", "CHANGELOG_RU.md"]:
    (ROOT / name).write_text((ROOT.parent / name).read_text())
